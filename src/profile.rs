use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::error::Error;
use std::fs;
use std::net::{IpAddr, SocketAddr};
use std::path::{Path, PathBuf};

use crate::cli::{RunArgs, SandboxArgs};
use crate::policy::{DEFAULT_CONFIG_FILE, Policy, PolicyFile, home_dir};
use crate::sandbox;
use crate::trace::{Category, EventKind, TraceEvent, read_events};

const FALLBACK_PROFILE_FILE: &str = "mcp-jail.profile.toml";
// Depth of the directory granted for an observed file: ~/.config/<tool>, /opt/<vendor>/<tool>
const HOME_GRANT_DEPTH: usize = 2;
const SYSTEM_GRANT_DEPTH: usize = 3;
// A single level (/etc, /dev, ~/.config) mixes unrelated tools' data, including secrets
const MIN_GRANT_DEPTH: usize = 2;
const PROFILE_HEADER: &str = "\
# Generated by `mcp-jail profile` from one observed session.
# Review before use: grants cover only what that session touched outside the built-in
# defaults, and allow_ips pins the addresses seen, which may change between runs.

";

/// Path -> needs write access
type Grants = BTreeMap<PathBuf, bool>;

pub fn run(run: &RunArgs) -> Result<i32, Box<dyn Error>> {
    let mut policy = Policy::load(&run.sandbox)?;
    policy.audit_only = true;
    policy.enforce_deny_patterns = true;
    let log_path = policy.log_path.clone();
    let exit_code = sandbox::run(&run.command, policy)?;
    let cwd = env::current_dir()?;
    let home = home_dir();
    let profile = build_profile(
        &read_events(&log_path)?,
        &baseline(&cwd, home.as_deref()),
        home.as_deref(),
    );
    let written = write_profile(&profile, &cwd)?;
    eprintln!(
        "mcp-jail: wrote {} ({} ro, {} rw, {} allowed IPs, deny_net={}, deny_exec={})",
        written.display(),
        profile.filesystem.ro.len(),
        profile.filesystem.rw.len(),
        profile.network.allow_ips.len(),
        profile.network.deny,
        profile.process.deny_exec
    );
    Ok(exit_code)
}

/// Built-in defaults only, so the profile lists everything a config file granted too
fn baseline(cwd: &Path, home: Option<&Path>) -> Policy {
    let mut policy = Policy::build(PolicyFile::default(), &SandboxArgs::default(), home);
    policy.resolve_paths(cwd);
    policy.drop_broad_grants(home);
    policy
}

pub fn build_profile(events: &[TraceEvent], baseline: &Policy, home: Option<&Path>) -> PolicyFile {
    let mut grants = Grants::new();
    let mut contacted_ips = BTreeSet::new();
    let mut has_exec = false;
    for event in events {
        let EventKind::SyscallEvent {
            category,
            target,
            write,
            ..
        } = &event.kind
        else {
            continue;
        };
        match category {
            Category::Fs => record_path(&mut grants, Path::new(target), *write, baseline, home),
            Category::Net => {
                if let Ok(address) = target.parse::<SocketAddr>() {
                    contacted_ips.insert(address.ip());
                }
            }
            Category::Process => has_exec = true,
        }
    }
    to_policy_file(&minimize(grants), contacted_ips, has_exec)
}

fn record_path(
    grants: &mut Grants,
    target: &Path,
    is_write: bool,
    baseline: &Policy,
    home: Option<&Path>,
) {
    if !target.is_absolute() {
        return;
    }
    let canonical = target
        .canonicalize()
        .unwrap_or_else(|_| target.to_path_buf());
    // Secrets stay blocked by deny_patterns regardless, so granting them would be noise
    let is_secret = baseline.is_denied_path(target) || baseline.is_denied_path(&canonical);
    if is_secret || baseline.is_path_allowed(&canonical, is_write) {
        return;
    }
    let needs_write = grants.entry(grant_path(&canonical, home)).or_insert(false);
    *needs_write |= is_write;
}

/// Collapses a file to a meaningful parent directory; when that directory would be a
/// top-level one, `$HOME` or an ancestor of `$HOME`, the exact file is granted instead
pub fn grant_path(path: &Path, home: Option<&Path>) -> PathBuf {
    let directory = if path.is_dir() {
        path
    } else {
        path.parent().unwrap_or(path)
    };
    let (root, depth) = match home {
        Some(home) if directory.starts_with(home) => (home, HOME_GRANT_DEPTH),
        _ => (Path::new("/"), SYSTEM_GRANT_DEPTH),
    };
    let relative = directory.strip_prefix(root).unwrap_or(directory);
    let collapsed = root.join(relative.components().take(depth).collect::<PathBuf>());
    let depth_below_root = collapsed
        .strip_prefix(root)
        .map_or(0, |rest| rest.components().count());
    let is_too_broad =
        depth_below_root < MIN_GRANT_DEPTH || home.is_some_and(|home| home.starts_with(&collapsed));
    if is_too_broad {
        path.to_path_buf()
    } else {
        collapsed
    }
}

/// Drops grants already covered by an ancestor with at least the same access
fn minimize(grants: Grants) -> Grants {
    let mut kept = Grants::new();
    for (path, needs_write) in grants {
        let is_covered = kept.iter().any(|(ancestor, ancestor_write)| {
            path.starts_with(ancestor) && (*ancestor_write || !needs_write)
        });
        if !is_covered {
            kept.insert(path, needs_write);
        }
    }
    kept
}

fn to_policy_file(grants: &Grants, contacted_ips: BTreeSet<IpAddr>, has_exec: bool) -> PolicyFile {
    let mut profile = PolicyFile::default();
    for (path, needs_write) in grants {
        let list = if *needs_write {
            &mut profile.filesystem.rw
        } else {
            &mut profile.filesystem.ro
        };
        list.push(path.clone());
    }
    profile.network.deny = contacted_ips.is_empty();
    profile.network.allow_ips = contacted_ips.into_iter().collect();
    profile.process.deny_exec = !has_exec;
    profile
}

/// Never overwrites an existing policy: the profile goes to a sibling file instead
fn write_profile(profile: &PolicyFile, cwd: &Path) -> Result<PathBuf, Box<dyn Error>> {
    let primary = cwd.join(DEFAULT_CONFIG_FILE);
    let target = if primary.exists() {
        cwd.join(FALLBACK_PROFILE_FILE)
    } else {
        primary
    };
    let body = toml::to_string_pretty(profile)?;
    fs::write(&target, format!("{PROFILE_HEADER}{body}"))
        .map_err(|e| format!("cannot write profile {}: {e}", target.display()))?;
    Ok(target)
}

