use std::path::{Path, PathBuf};

use super::*;
use crate::trace::parse_line;

const HOME: &str = "/home/tester";

fn event(category: &str, target: &str, write: bool) -> TraceEvent {
    parse_line(&format!(
        r#"{{"ts_ms":1,"type":"syscall_event","action":"audited","category":"{category}","syscall":"x","target":"{target}","pid":1,"mcp_context":"idle","write":{write}}}"#
    ))
    .unwrap()
}

fn baseline_policy() -> Policy {
    let mut policy = Policy::build(
        PolicyFile::default(),
        &SandboxArgs::default(),
        Some(Path::new(HOME)),
    );
    policy.resolve_paths(&std::env::temp_dir());
    policy
}

fn profile(events: &[TraceEvent]) -> PolicyFile {
    build_profile(events, &baseline_policy(), Some(Path::new(HOME)))
}

#[test]
fn grant_path_collapses_to_meaningful_directories() {
    let home = Some(Path::new(HOME));
    let config = grant_path(Path::new("/home/tester/.config/gh/hosts.yml"), home);
    assert_eq!(config, PathBuf::from("/home/tester/.config/gh"));
    let vendor = grant_path(Path::new("/opt/vendor/tool/lib/data.bin"), home);
    assert_eq!(vendor, PathBuf::from("/opt/vendor/tool"));
}

#[test]
fn grant_path_never_grants_root_or_home() {
    let home = Some(Path::new(HOME));
    let in_home = Path::new("/home/tester/.gitconfig");
    assert_eq!(grant_path(in_home, home), in_home);
    let at_root = Path::new("/package.json");
    assert_eq!(grant_path(at_root, home), at_root);
    let above_home = Path::new("/home/shared.txt");
    assert_eq!(grant_path(above_home, home), above_home);
    for top_level_file in [
        "/etc/gitconfig",
        "/dev/tty",
        "/home/tester/.config/app.json",
    ] {
        assert_eq!(
            grant_path(Path::new(top_level_file), home),
            Path::new(top_level_file)
        );
    }
    let nested = grant_path(Path::new("/var/lib/tool/db/x.sqlite"), home);
    assert_eq!(nested, PathBuf::from("/var/lib/tool"));
}

#[test]
fn builds_least_privilege_policy() {
    let events = [
        event("fs", "/opt/vendor/tool/a.bin", false),
        event("fs", "/opt/vendor/tool/sub/b.bin", false),
        event("fs", "/home/tester/.cache/tool/state.db", true),
        event("fs", "/usr/lib/libc.so", false),
        event("fs", concat!("/home/tester/.ss", "h/id_ed25519"), false),
        event("net", "140.82.121.4:443", false),
    ];
    let profile = profile(&events);
    assert_eq!(
        profile.filesystem.ro,
        vec![PathBuf::from("/opt/vendor/tool")]
    );
    assert_eq!(
        profile.filesystem.rw,
        vec![PathBuf::from("/home/tester/.cache/tool")]
    );
    assert_eq!(
        profile.network.allow_ips,
        vec!["140.82.121.4".parse::<IpAddr>().unwrap()]
    );
    assert!(!profile.network.deny);
    assert!(profile.process.deny_exec);
}

#[test]
fn write_access_upgrades_a_read_grant() {
    let events = [
        event("fs", "/opt/vendor/tool/a.bin", false),
        event("fs", "/opt/vendor/tool/b.log", true),
        event("process", "/usr/bin/git", false),
    ];
    let profile = profile(&events);
    assert!(profile.filesystem.ro.is_empty());
    assert_eq!(
        profile.filesystem.rw,
        vec![PathBuf::from("/opt/vendor/tool")]
    );
    assert!(profile.network.deny);
    assert!(!profile.process.deny_exec);
}

#[test]
fn written_profile_round_trips_and_never_overwrites() {
    let dir = tempfile::tempdir().unwrap();
    let profile = profile(&[event("fs", "/opt/vendor/tool/a.bin", false)]);
    let first = write_profile(&profile, dir.path()).unwrap();
    assert_eq!(first, dir.path().join(DEFAULT_CONFIG_FILE));
    let second = write_profile(&profile, dir.path()).unwrap();
    assert_eq!(second, dir.path().join(FALLBACK_PROFILE_FILE));
    let text = std::fs::read_to_string(first).unwrap();
    assert!(text.starts_with("# Generated by `mcp-jail profile`"));
    let parsed: PolicyFile = toml::from_str(&text).unwrap();
    assert_eq!(parsed, profile);
}
